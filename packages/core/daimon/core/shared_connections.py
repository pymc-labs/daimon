FEATURE: Final = "shared_connections"
ASK_FEATURE: Final = "shared_write_approval"
#: The tag of every served tool: listed by name, not behind search, and open to agent keys.
SERVED_TAG: Final = "shared-connection"
"""Whether a shared write asks on a card in chat: on (`ask`) by default."""
WRITE_NOTE: Final = "This tool changes things. Ask your user and get their yes before you call it."
NAME_PATTERN: Final = re.compile(r"[a-z0-9][a-z0-9-]{0,31}")
"""A connection name carries no underscore: the first one in `<connection>_<tool>` ends it."""
SCOPE_PATTERN: Final = re.compile(r"[a-z0-9][a-z0-9_.:-]{0,63}")
_SERVED = re.compile(r"[A-Za-z0-9_.-]{1,128}")
_TOKEN_MAX = 4096
_TOOLS_MAX = 200
_DESCRIPTION_MAX = 2000
_SCHEMA_MAX = 16_000
"""Characters of a tool's input schema as JSON; a larger one is left out."""
_RESULT_MAX = 100_000
DAIMON_TOOL_NAMES: Final = frozenset(
    {"call_tool", "search_tools"}  # the tool search's own two
    | set(files("daimon.core").joinpath("daimon_tool_names.txt").read_text().split())
)
"""Daimon's own `/mcp` tool names, generated by `scripts/generate_mcp_tool_catalogue.py`."""

OpenUpstream = Callable[[str, str | None], AbstractAsyncContextManager[McpToolSession]]


def open_upstream(url: str, token: str | None) -> AbstractAsyncContextManager[McpToolSession]:
    return mcp_tool_session(url, token, limits=INTERACTIVE_LIMITS)


ErrorKind = Literal["invalid", "conflict", "read_only", "missing"]


class SharedConnectionError(Exception):
    """A connection could not be added, read or called; the message is safe to show.
    `kind` says why: a bad value, a change that raced another, a declared connection or
    a connection or tool that isn't there."""

    def __init__(self, message: str, kind: ErrorKind = "invalid") -> None:
        super().__init__(message)
        self.kind: ErrorKind = kind


@dataclass(frozen=True, slots=True)
class SharedCaller:
    """Who asks: what the data package's scope check needs, and nothing else."""

    tenant_id: uuid.UUID
    account_id: uuid.UUID | None
    platform: str | None = None
    chat_session_id: str | None = None


class ScopeCheck(Protocol):
    """Whether `caller` holds data scope `scope`, asked of the audience the call runs for."""

    async def __call__(self, caller: SharedCaller, scope: str) -> bool: ...


async def _no_scopes(caller: SharedCaller, scope: str) -> bool:
    return False


_scope_check: ScopeCheck = _no_scopes


def register_scope_check(check: ScopeCheck | None) -> None:
    """Set the scope check, once at start (the data package); None restores the refusal."""
    global _scope_check
    _scope_check = check or _no_scopes


@dataclass(frozen=True, slots=True)
class SharedTool:
    """An approved tool a caller may use, under the name it is served as."""

    name: str
    connection: McpConnectionRow
    tool: McpConnectionToolRow


def is_served_name(name: str) -> bool:
    return _SERVED.fullmatch(name) is not None


def _served_name(connection: str, tool: str) -> str | None:
    name = f"{connection}_{tool}"
    return name if _SERVED.fullmatch(name) else None


async def shared_connections_on(
    sessions: Sessions, settings: Settings | None, places: Sequence[FeaturePlace]
) -> bool:
    """Whether the feature is on at every place the call may run; a failed read is off."""
    if not places:
        return False
    for place in places:
        found = await place_feature_or_none(sessions, settings, place, "shared_connections")
        if found is None or not found.on:
            return False
    return True


async def served_tools(session: AsyncSession, caller: SharedCaller) -> list[SharedTool]:
    """The tools `caller` may see: approved and unchanged since, on an active connection,
    within both scopes, under a name no Daimon tool has. A web visitor sees none."""
    rows = await store.list_served(session, tenant_id=caller.tenant_id)
    if caller.account_id is None or not rows:
        return []
    person = await get_person_for_account(
        session, tenant_id=caller.tenant_id, account_id=caller.account_id
    )
    if person is not None and person.kind == "visitor":
        return []
    allowed: dict[str, bool] = {}

    async def within(scope: str | None) -> bool:
        if scope is None:
            return True
        if scope not in allowed:
            allowed[scope] = await _scope_check(caller, scope)
        return allowed[scope]

    out: list[SharedTool] = []
    taken: set[str] = set()  # the first connection, by name, keeps a served name
    for connection, tool in rows:
        name = _served_name(connection.name, tool.name)
        if name is None or name in DAIMON_TOOL_NAMES or name in taken:
            continue
        taken.add(name)
        if not tool.changed and await within(connection.scope) and await within(tool.scope):
            out.append(SharedTool(name, connection, tool))
    return out


def decide_shared_call(
    policy: ToolSafetyPolicy,
    name: str,
    arguments: dict[str, object],
    *,
    writes: bool,
    attended: bool,
    agent_rule: ResolvedAgentToolRule | None,
    outside: bool = False,
    data_read: bool = False,
    ask_writes: bool = True,
) -> ToolVerdict:
    """Run, ask or refuse one call by the rules for any third-party tool: never trusted, a
    write asks (and is refused unattended), the operator's and the agent's rules apply.
    `name` is the served name; `writes` is the tool's flag. An `outside` client (the hub, a
    key, a CLI) has no card: it asks its own user, as the tool's description tells it, so
    what would ask runs. With `ask_writes` off (`ASK_FEATURE`) a write in chat runs unasked;
    unattended it is still refused unless the operator allows it. After a `data_read`, any
    call that would run asks, or is refused unattended: its arguments go to a third party."""
    call = ToolCall(
        tool_use_id=f"shared-{uuid.uuid4()}",
        server_name=DAIMON_SERVER_NAME,
        tool_name=name,
        input=arguments,
    )
    # A shared write asks whatever the operator's global switch for tools; `ask_writes` is
    # the one switch for these.
    verdict = decide_tool_call(
        policy.model_copy(update={"enabled": True}),
        call,
        attended=attended or outside,
        trusted_servers=frozenset(),
        annotations=ToolAnnotations(read_only_hint=not writes, destructive_hint=None),
        agent_rule=agent_rule,
    )
    if verdict.outcome == "ask" and (
        outside or (not ask_writes and verdict.reason == "write_needs_confirmation")
    ):
        verdict = ToolVerdict(outcome="allow", effect=verdict.effect, reason="approval_skipped")
    if data_read and verdict.outcome == "allow":
        return ToolVerdict(
            outcome="ask" if attended else "deny", effect="write", reason="data_read"
        )
    return verdict


def shown_description(shared: SharedTool, *, outside: bool) -> str:
    """The approved description; for an outside client a write also says to ask first."""
    text = shared.tool.description or f"{shared.connection.name}: {shared.tool.name}"
    return f"{text}\n\n{WRITE_NOTE}" if outside and shared.tool.writes else text


def seen_digest(tool: McpConnectionToolRow) -> str:
    """A short fingerprint of what the upstream shows now and whether the tool writes, to
    approve exactly those."""
    text = json.dumps([tool.seen_description, tool.seen_schema, tool.writes], sort_keys=True)
    return hashlib.sha256(text.encode()).hexdigest()[:16]


async def approve_tool(
    session: AsyncSession,
    *,
    tenant_id: uuid.UUID,
    connection_id: uuid.UUID,
    name: str,
    seen: str,
) -> None:
    """Serve a tool under the description, schema and effect the admin was shown
    (`seen_digest`)."""
    rows = await store.list_tools(session, tenant_id=tenant_id, connection_id=connection_id)
    tool = next((t for t in rows if t.name == name), None)
    if tool is None:
        raise SharedConnectionError("This tool isn't here.", "conflict")
    if seen_digest(tool) != seen:
        raise SharedConnectionError(
            "The server changed this tool just now. Review it again.", "conflict"
        )
    await store.update_tool(
        session,
        tenant_id=tenant_id,
        connection_id=connection_id,
        name=name,
        values={
            "description": tool.seen_description,
            "input_schema": tool.seen_schema,
            "approved_writes": tool.writes,
            "enabled": True,
        },
    )


def _clean_token(token: str | None) -> str | None:
    if token is None or not token.strip():
        return None
    token = token.strip()
    if len(token) > _TOKEN_MAX or not token.isprintable() or " " in token:
        raise SharedConnectionError("The token isn't valid.")
    return token


def encrypt_auth(fernet: MultiFernet, token: str) -> bytes | None:
    """The stored form of a token; None for a blank one."""
    clean = _clean_token(token)
    return None if clean is None else encrypt_token(fernet, clean)


def reveal_auth(fernet: MultiFernet, connection: McpConnectionRow) -> str | None:
    return (
        None
        if connection.encrypted_auth is None
        else decrypt_token(fernet, connection.encrypted_auth)
    )


def checked_address(url: str) -> str:
    """`url` as stored: public https, its host in ascii, no credentials and no query (a key
    there would sit in plain text)."""
    try:
        address = ascii_mcp_url(assert_public_https_url(url.strip(), what="address"))
        parts = urlsplit(address)
        if "@" in parts.netloc or parts.query or not address.isascii():
            raise McpUrlError("address has credentials, a query or a host that won't encode")
    except McpUrlError as err:
        raise SharedConnectionError(
            "The address must be a public https address with no query."
        ) from err
    return address


async def add_connection(
    session: AsyncSession,
    fernet: MultiFernet,
    *,
    tenant_id: uuid.UUID,
    name: str,
    url: str,
    token: str | None,
    scope: str | None = None,
) -> McpConnectionRow:
    """Store a connection; the address must be public https and the name unused."""
    if NAME_PATTERN.fullmatch(name) is None:
        raise SharedConnectionError("Use lowercase letters, digits and dashes in the name.")
    address = checked_address(url)
    taken = SharedConnectionError("A connection with this name already exists.")
    if await store.get_connection_by_name(session, tenant_id=tenant_id, name=name) is not None:
        raise taken
    try:
        return await store.create_connection(
            session,
            tenant_id=tenant_id,
            name=name,
            url=address,
            encrypted_auth=None if token is None else encrypt_auth(fernet, token),
            scope=scope,
        )
    except IntegrityError as err:  # an add of the same name just now
        raise taken from err


def _printable(text: str) -> str:
    return "".join(ch for ch in text if ch == "\n" or ch.isprintable())


def _discovered(
    policy: ToolSafetyPolicy,
    connection: str,
    listed: tuple[dict[str, JsonValue], ...],
    taken: frozenset[str] = frozenset(),
) -> tuple[list[DiscoveredTool], list[str]]:
    """The tools to store, and those left out with why: a Daimon tool's name, a name another
    connection serves (`taken`), a schema that is not an object or past `_SCHEMA_MAX`, and
    any past the first `_TOOLS_MAX`. Descriptions lose control and bidi characters."""
    found: list[DiscoveredTool] = []
    left_out: list[str] = []
    for item in listed:
        name, description, schema = (
            item.get("name"),
            item.get("description"),
            item.get("inputSchema"),
        )
        served = _served_name(connection, name) if isinstance(name, str) else None
        if not isinstance(name, str) or served is None:
            continue
        schema: JsonValue = {"type": "object"} if schema is None else schema
        if served in DAIMON_TOOL_NAMES:
            left_out.append(f"{served} (a Daimon tool's name)")
            continue
        if served in taken:
            left_out.append(f"{served} (served by another connection)")
            continue
        if len(found) >= _TOOLS_MAX:
            left_out.append(f"{served} (past the first {_TOOLS_MAX})")
            continue
        if (
            not isinstance(schema, dict)
            or schema.get("type") != "object"
            or len(json.dumps(schema)) > _SCHEMA_MAX
        ):
            left_out.append(f"{served} (arguments too large or not an object)")
            continue
        # Daimon's name rule (or the operator's override), never the upstream's own hints.
        effect = classify_tool(policy, server_name=DAIMON_SERVER_NAME, tool_name=name)
        found.append(
            DiscoveredTool(
                name=name,
                description=_printable(description if isinstance(description, str) else "")[
                    :_DESCRIPTION_MAX
                ],
                input_schema=schema,
                writes=effect == "write",
            )
        )
    return found, left_out


async def refresh_connection(
    sessions: Sessions,
    fernet: MultiFernet,
    policy: ToolSafetyPolicy,
    connection: McpConnectionRow,
    *,
    open_session: OpenUpstream | None = None,
) -> int:
    """Read the upstream's tool list into the store; how it went is kept on the connection,
    with the tools left out. A paused connection stays paused."""
    try:
        async with (open_session or open_upstream)(
            connection.url, reveal_auth(fernet, connection)
        ) as upstream:
            listed = await upstream.list_tools()
    except McpCallError as err:
        async with sessions.begin() as session:
            await store.mark_connection(
                session,
                tenant_id=connection.tenant_id,
                connection_id=connection.id,
                status="error",
                last_error=f"The server could not be read ({err.kind}).",
            )
        raise SharedConnectionError("The server could not be read.") from err
    async with sessions() as session:
        others = {
            c.id: c.name
            for c in await store.list_connections(session, tenant_id=connection.tenant_id)
        }
        tools = await store.list_tools(session, tenant_id=connection.tenant_id)
    taken = frozenset(
        f"{others[t.connection_id]}_{t.name}"
        for t in tools
        if t.connection_id != connection.id and t.connection_id in others
    )
    found, left_out = _discovered(policy, connection.name, listed, taken)
    more = f" and {len(left_out) - 10} more" if len(left_out) > 10 else ""
    note = f"Left out: {', '.join(left_out[:10])}{more}." if left_out else None
    async with sessions.begin() as session:
        await store.sync_tools(
            session, tenant_id=connection.tenant_id, connection_id=connection.id, discovered=found
        )
        await store.record_refresh(
            session, tenant_id=connection.tenant_id, connection_id=connection.id, note=note
        )
    return len(found)


@dataclass(frozen=True, slots=True)
class SharedResult:
    """What the upstream answered, as plain text: no images, links or embedded resources."""

    text: str
    is_error: bool


def _result_of(raw: dict[str, JsonValue]) -> SharedResult:
    content = raw.get("content")
    parts: list[str] = []
    for item in content if isinstance(content, list) else []:
        if (
            isinstance(item, dict)
            and item.get("type") == "text"
            and isinstance(item.get("text"), str)
        ):
            parts.append(str(item["text"]))
        else:
            parts.append("[content that is not text was left out]")
    text = "\n".join(parts)
    if not text and raw.get("structuredContent") is not None:
        text = json.dumps(raw["structuredContent"])
    return SharedResult(text[:_RESULT_MAX] or "Done.", raw.get("isError") is True)


async def call_upstream(
    fernet: MultiFernet,
    shared: SharedTool,
    arguments: dict[str, JsonValue],
    *,
    open_session: OpenUpstream | None = None,
) -> SharedResult:
    """Call the connection's tool by its own name; an unreachable server is one safe message."""
    try:
        async with (open_session or open_upstream)(
            shared.connection.url, reveal_auth(fernet, shared.connection)
        ) as up:
            return _result_of(await up.call_tool_result(shared.tool.name, arguments))
    except McpCallError as err:
        raise SharedConnectionError("The connection didn't answer. Try again later.") from err


async def find_connection(
    db: AsyncSession, tenant_id: uuid.UUID, ref: str
) -> McpConnectionRow | None:
    """A connection by its id or its name, as listed."""
    try:
        return await store.get_connection(
            db, tenant_id=tenant_id, connection_id=uuid.UUID(ref.strip())
        )
    except ValueError:
        return await store.get_connection_by_name(db, tenant_id=tenant_id, name=ref.strip())


def card_lookup(
    sessions: Sessions, *, tenant_id: uuid.UUID
) -> Callable[[ToolCall], Awaitable[SharedConnectionCard | None]]:
    """What a chat change names, from the store: `None` when it is gone, or when turn_on's
    `seen` no longer matches what the upstream shows."""

    async def _lookup(call: ToolCall) -> SharedConnectionCard | None:
        data = call.input
        if call.tool_name == "change_shared_connection" and data.get("action") == "add":
            return SharedConnectionCard(
                str(data.get("name") or ""), shown_mcp_url(str(data.get("url") or ""))
            )
        async with sessions() as db:
            row = await find_connection(db, tenant_id, str(data.get("connection") or ""))
            if row is None:
                return None
            card = SharedConnectionCard(row.name, shown_mcp_url(row.url))
            if call.tool_name == "change_shared_connection":
                return card
            tools = await store.list_tools(db, tenant_id=tenant_id, connection_id=row.id)
        tool = next((t for t in tools if t.name == data.get("tool")), None)
        if tool is None:
            return None
        if data.get("action") != "turn_on":
            return replace(card, tool=tool.name, description=tool.description, writes=tool.writes)
        if data.get("seen") != seen_digest(tool):
            return None
        return replace(card, tool=tool.name, description=tool.seen_description, writes=tool.writes)

    return _lookup
